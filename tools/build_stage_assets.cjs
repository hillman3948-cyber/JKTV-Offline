/* Run after editing app/src/main/stage-src. Generated assets are checked in; Gradle needs no Node/network. */
const fs=require('fs'),path=require('path'),esbuild=require('./stage-build/node_modules/esbuild');
const root=path.resolve(__dirname,'..');
for(const name of ['stage-client.js','stage-audio.js','stage-remote.js','stage-link.js','stage-worker.js','stage-pcm.js']){
  const source=fs.readFileSync(path.join(root,'app/src/main/stage-src',name),'utf8');
  const result=esbuild.transformSync(source,{target:'chrome56',legalComments:'inline',banner:'/* Generated by tools/build_stage_assets.cjs; edit app/src/main/stage-src/'+name+' */'});
  fs.writeFileSync(path.join(root,'app/src/main/assets/stage',name),result.code);
}
fs.copyFileSync(path.join(root,'tools/stage-compat.js'),path.join(root,'app/src/main/assets/stage/stage-compat.js'));
console.log('Built Stage, audio and remote assets for Chromium 56 syntax.');
